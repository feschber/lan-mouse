//! Access to the OS clipboard (blocking; call from `spawn_blocking`).

use std::{path::PathBuf, thread};

use clipboard_rs::{
    Clipboard, ClipboardContent, ClipboardContext, ClipboardHandler, ClipboardWatcher,
    ClipboardWatcherContext, ContentFormat, RustImageData, common::RustImage,
};
use sha2::{Digest, Sha256};
use tokio::sync::mpsc::UnboundedSender;

use super::proto::ClipKind;

/// Formats password managers put on the clipboard to ask clipboard tools
/// to leave the contents alone.
const PRIVATE_FORMATS: &[&str] = &[
    // macOS, see nspasteboard.org
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    // Windows
    "ExcludeClipboardContentFromMonitorProcessing",
];

pub(crate) enum ClipData {
    Parts(Vec<(ClipKind, Vec<u8>)>),
    Files(Vec<PathBuf>),
}

impl ClipData {
    /// Identifies contents, to recognise our own writes coming back.
    pub(crate) fn digest(&self) -> [u8; 32] {
        let mut h = Sha256::new();
        match self {
            ClipData::Parts(parts) => {
                // Images are re-encoded by the OS, so only text-like parts
                // identify contents reliably; fall back to images otherwise.
                let texty: Vec<_> = parts.iter().filter(|(k, _)| *k == ClipKind::Text).collect();
                let parts: Vec<_> = if texty.is_empty() {
                    parts.iter().collect()
                } else {
                    texty
                };
                for (kind, data) in parts {
                    h.update(format!("{kind:?}:{}:", data.len()));
                    h.update(data);
                }
            }
            ClipData::Files(files) => {
                for f in files {
                    h.update(b"file:");
                    h.update(f.to_string_lossy().as_bytes());
                    h.update(b"\0");
                }
            }
        }
        h.finalize().into()
    }

    pub(crate) fn describe(&self) -> String {
        match self {
            ClipData::Parts(parts) => {
                let kinds: Vec<_> = parts
                    .iter()
                    .map(|(k, d)| format!("{k:?} {}B", d.len()))
                    .collect();
                kinds.join(", ")
            }
            ClipData::Files(f) => format!("{} file(s)", f.len()),
        }
    }
}

fn context() -> Option<ClipboardContext> {
    match ClipboardContext::new() {
        Ok(c) => Some(c),
        Err(e) => {
            log::warn!("clipboard unavailable: {e}");
            None
        }
    }
}

/// Read the clipboard. `None` if it is empty, private or unreadable.
pub(crate) fn read() -> Option<ClipData> {
    let ctx = context()?;
    if let Ok(formats) = ctx.available_formats() {
        if formats
            .iter()
            .any(|f| PRIVATE_FORMATS.contains(&f.as_str()))
        {
            log::debug!("clipboard holds private data, not sharing it");
            return None;
        }
    }
    if ctx.has(ContentFormat::Files) {
        if let Ok(files) = ctx.get_files() {
            let files: Vec<PathBuf> = files
                .into_iter()
                .map(|f| PathBuf::from(f.strip_prefix("file://").unwrap_or(&f)))
                .filter(|p| p.exists())
                .collect();
            if !files.is_empty() {
                return Some(ClipData::Files(files));
            }
        }
    }
    let mut parts = Vec::new();
    if ctx.has(ContentFormat::Text) {
        if let Ok(t) = ctx.get_text() {
            if !t.is_empty() {
                parts.push((ClipKind::Text, t.into_bytes()));
            }
        }
    }
    if ctx.has(ContentFormat::Html) {
        if let Ok(t) = ctx.get_html() {
            if !t.is_empty() {
                parts.push((ClipKind::Html, t.into_bytes()));
            }
        }
    }
    if ctx.has(ContentFormat::Rtf) {
        if let Ok(t) = ctx.get_rich_text() {
            if !t.is_empty() {
                parts.push((ClipKind::Rtf, t.into_bytes()));
            }
        }
    }
    if ctx.has(ContentFormat::Image) {
        match ctx.get_image().and_then(|i| i.to_png()) {
            Ok(png) => parts.push((ClipKind::Png, png.get_bytes().to_vec())),
            Err(e) => log::debug!("clipboard image unreadable: {e}"),
        }
    }
    if parts.is_empty() {
        None
    } else {
        Some(ClipData::Parts(parts))
    }
}

pub(crate) fn write(data: &ClipData) -> Result<(), String> {
    let ctx = context().ok_or("clipboard unavailable")?;
    match data {
        ClipData::Files(files) => ctx
            .set_files(
                files
                    .iter()
                    .map(|f| f.to_string_lossy().into_owned())
                    .collect(),
            )
            .map_err(|e| e.to_string()),
        ClipData::Parts(parts) => {
            let mut contents = Vec::new();
            for (kind, data) in parts {
                let text = || String::from_utf8_lossy(data).into_owned();
                match kind {
                    ClipKind::Text => contents.push(ClipboardContent::Text(text())),
                    ClipKind::Html => contents.push(ClipboardContent::Html(text())),
                    ClipKind::Rtf => contents.push(ClipboardContent::Rtf(text())),
                    ClipKind::Png => match RustImageData::from_bytes(data) {
                        Ok(img) => contents.push(ClipboardContent::Image(img)),
                        Err(e) => log::warn!("received image is invalid: {e}"),
                    },
                }
            }
            ctx.set(contents).map_err(|e| e.to_string())
        }
    }
}

struct Notify(UnboundedSender<()>);

impl ClipboardHandler for Notify {
    fn on_clipboard_change(&mut self) {
        let _ = self.0.send(());
    }
}

/// Watch the clipboard on a thread of its own; sends `()` on every change.
pub(crate) fn watch(tx: UnboundedSender<()>) {
    thread::Builder::new()
        .name("clipboard-watch".into())
        .spawn(move || {
            let mut watcher = match ClipboardWatcherContext::new() {
                Ok(w) => w,
                Err(e) => {
                    log::warn!("cannot watch the clipboard: {e}");
                    return;
                }
            };
            watcher.add_handler(Notify(tx));
            watcher.start_watch();
        })
        .expect("spawn clipboard watcher");
}
